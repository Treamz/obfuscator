/// Resolved `lib` file of an obfuscated package, prepared for merging.
///
class _MergedSource {
  _MergedSource({
    required this.package,
    required this.filePath,
    required this.result,
  });

  final SourcePackage package;

  final String filePath;

  final analyzer_results.ResolvedUnitResult result;

  /// Text replacements applied to the file contents before merging.
  ///
  /// Edits at the same offset are applied by their `priority` (lower first), then in the order of addition.
  ///
  final edits = <({int offset, int end, String text, int priority, int order})>[];

  final _editKeys = <(int, int, String)>{};

  void addEdit(int offset, int end, String text, {int priority = 1}) {
    if (_editKeys.add((offset, end, text))) {
      edits.add((offset: offset, end: end, text: text, priority: priority, order: edits.length));
    }
  }
}

/// Third-party library exported by a merged library, with the combinators applied to it, in the order of application.
///
typedef _Export = ({analyzer_element.LibraryElement library, List<analyzer_element.NamespaceCombinator> combinators});

/// Import directive of the merged file.
///
class _MergedImport {
  _MergedImport({
    required this.source,
    required this.libraryKey,
    required this.prefix,
    required this.isDeferred,
    required String Function(String? prefix) render,
  }) : originalPrefix = prefix,
       _render = render;

  /// Import prefix declared by the merged file.
  ///
  final String? originalPrefix;

  /// The merged file which declared the import, or `null` for the imports generated by the merger.
  ///
  final _MergedSource? source;

  /// Identifier of the imported library.
  ///
  final String libraryKey;

  /// Import prefix, which may be renamed to avoid clashes between the merged files.
  ///
  String? prefix;

  /// Whether the library is loaded lazily.
  ///
  final bool isDeferred;

  final String Function(String? prefix) _render;

  /// Source code of the directive.
  ///
  String get text => _render(prefix);
}

/// Reference to a top-level declaration, which may require renaming or a prefix in the merged file.
///
class _TopLevelReference {
  _TopLevelReference({
    required this.source,
    required this.offset,
    required this.end,
    required this.element,
    required this.isSimpleInterpolation,
  });

  final _MergedSource source;

  final int offset;

  final int end;

  final analyzer_element.Element element;

  /// Whether the reference is a simple string interpolation (e.g., `$name`), which can't be prefixed as it is.
  ///
  final bool isSimpleInterpolation;
}

/// Class used for merging all of the available source code directories into a single file.
///
class ProjectMerger {
  /// Class used for merging all of the available source code directories into a single file,
  /// according to the provided [configuration].
  ///
  ProjectMerger({
    required Configuration configuration,
    required ObjectCollector collector,
  }) : _configuration = configuration,
       _collector = collector;

  /// Object defining the basic input options for the obfuscation service.
  ///
  final Configuration _configuration;

  /// Property holding the value of the main object collector.
  ///
  final ObjectCollector _collector;

  /// Whether the [library] is one of the obfuscated libraries, merged into the output file.
  ///
  bool _isMergedLibrary(analyzer_element.LibraryElement? library) {
    if (library == null) return false;
    final uri = library.uri;
    if (uri.scheme == 'package') {
      return uri.pathSegments.isNotEmpty && _configuration.sourcePackages.contains(uri.pathSegments.first);
    }
    if (uri.scheme == 'file') {
      final filePath = uri.toFilePath();
      return _configuration.packages.any((package) => path.isWithin(path.join(package.copyDirectory.path, 'lib'), filePath));
    }
    return false;
  }

  /// Returns the top-level declaration an [element] reference resolves to, if any.
  ///
  static analyzer_element.Element? _topLevelElement(analyzer_element.Element? element) {
    if (element == null) return null;
    var base = element.baseElement;
    if (base is analyzer_element.ConstructorElement) return null;
    if (base is analyzer_element.PropertyAccessorElement) base = base.variable;
    if (base is analyzer_element.PrefixElement || base is analyzer_element.LibraryElement) return null;
    if (base.enclosingElement is! analyzer_element.LibraryElement) return null;
    final name = base.name;
    if (name == null || name.isEmpty || base.library == null) return null;
    return base;
  }

  /// Unique identifier of a top-level [element].
  ///
  static String _topLevelKey(analyzer_element.Element element) => '${element.library!.uri}#${element.name}';

  /// Resolves the `lib` files of the obfuscated packages.
  ///
  Future<List<_MergedSource>> _resolveSources(analyzer_context.AnalysisContextCollection collection) async {
    final sources = <_MergedSource>[];
    for (final package in _configuration.packages) {
      for (final filePath in ObjectCollector.listDartFiles(package)) {
        if (!ObjectCollector.isLibraryFile(package, filePath) || _collector.invalidFiles.contains(filePath)) continue;
        final context = ObjectCollector.contextFor(collection, filePath);
        final result = await context.currentSession.getResolvedUnit(filePath);
        if (result is! analyzer_results.ResolvedUnitResult) {
          throw ConfigurationException('Unable to analyze "$filePath" for merging: ${result.runtimeType}.');
        }
        sources.add(_MergedSource(package: package, filePath: filePath, result: result));
      }
    }
    return sources;
  }

  /// Collects the directive removals, and the references to top-level declarations.
  ///
  List<_TopLevelReference> _prepareSources(
    List<_MergedSource> sources,
    List<_MergedImport> imports,
  ) {
    final references = <_TopLevelReference>[];
    for (final source in sources) {
      final scriptTag = source.result.unit.scriptTag;
      if (scriptTag != null) source.addEdit(scriptTag.offset, scriptTag.end, '');
      for (final directive in source.result.unit.directives) {
        if (directive is analyzer_ast.ImportDirective) {
          final importedLibrary = directive.libraryImport?.importedLibrary;
          final prefix = directive.prefix?.name;
          if (!_isMergedLibrary(importedLibrary)) {
            imports.add(
              _MergedImport(
                source: source,
                libraryKey: importedLibrary?.uri.toString() ?? directive.uri.toSource(),
                prefix: prefix,
                isDeferred: directive.deferredKeyword != null,
                render: (prefix) => [
                  'import ${directive.uri.toSource()}',
                  for (final configuration in directive.configurations) configuration.toSource(),
                  if (directive.deferredKeyword != null) 'deferred',
                  if (prefix != null) 'as $prefix',
                  for (final combinator in directive.combinators) combinator.toSource(),
                ].join(' '),
              ),
            );
            if (importedLibrary == null) {
              print('Warning: unresolved import "${directive.uri.stringValue}" in ${source.filePath}.');
            }
          } else {
            // Third-party libraries re-exported by the merged library are imported directly, with the same
            // prefix and combinators. Deferred loading is dropped, as the merged library is always loaded.
            for (final export in _externalExports(importedLibrary!)) {
              imports.add(
                _MergedImport(
                  source: source,
                  libraryKey: export.library.uri.toString(),
                  prefix: prefix,
                  isDeferred: false,
                  render: (prefix) => [
                    "import '${export.library.uri}'",
                    if (prefix != null) 'as $prefix',
                    for (final combinator in export.combinators) _combinatorSource(combinator),
                    for (final combinator in directive.combinators) combinator.toSource(),
                  ].join(' '),
                ),
              );
            }
          }
        }
        source.addEdit(directive.offset, _endOfTrailingComment(source.result.content, directive.end), '');
      }
      source.result.unit.accept(
        _MergeReferenceVisitor(
          merger: this,
          source: source,
          references: references,
        ),
      );
    }
    return references;
  }

  /// Import prefix tokens of the references to third-party libraries, which are kept in the merged file.
  ///
  final _prefixUsages = <({_MergedSource source, analyzer_token.Token token})>[];

  /// Source code of a [combinator].
  ///
  static String _combinatorSource(analyzer_element.NamespaceCombinator combinator) {
    return switch (combinator) {
      analyzer_element.ShowElementCombinator(:final shownNames) => 'show ${shownNames.join(', ')}',
      analyzer_element.HideElementCombinator(:final hiddenNames) => 'hide ${hiddenNames.join(', ')}',
    };
  }

  /// Whether the [name] is visible through all of the [combinators].
  ///
  static bool _isVisible(String name, List<analyzer_element.NamespaceCombinator> combinators) {
    return combinators.every(
      (combinator) => switch (combinator) {
        analyzer_element.ShowElementCombinator(:final shownNames) => shownNames.contains(name),
        analyzer_element.HideElementCombinator(:final hiddenNames) => !hiddenNames.contains(name),
      },
    );
  }

  /// Top-level declarations visible through the [export], mapped by their names.
  ///
  static Map<String, analyzer_element.Element> _exportedElements(_Export export) {
    return {
      for (final entry in export.library.exportNamespace.definedNames2.entries)
        if (_topLevelElement(entry.value) case final element?)
          if (_isVisible(entry.key.replaceAll('=', ''), export.combinators)) entry.key.replaceAll('=', ''): element,
    };
  }

  /// Third-party libraries exported by the merged libraries, mapped by the exporting library URIs.
  ///
  final _externalExportsCache = <Uri, List<_Export>>{};

  /// Third-party libraries exported by the merged [library], directly or through other merged libraries.
  ///
  /// Each export path is followed, so that the combinators of all of the paths are applied.
  ///
  List<_Export> _externalExports(analyzer_element.LibraryElement library) => _collectExternalExports(library, {}).exports;

  /// Collects the third-party exports of the [library], skipping the libraries [inProgress] (export cycles).
  ///
  /// The results are cached, unless an export cycle was skipped while collecting them.
  ///
  ({List<_Export> exports, bool isComplete}) _collectExternalExports(
    analyzer_element.LibraryElement library,
    Set<Uri> inProgress,
  ) {
    final cached = _externalExportsCache[library.uri];
    if (cached != null) return (exports: cached, isComplete: true);
    inProgress.add(library.uri);
    var isComplete = true;
    final exports = <String, _Export>{};
    void add(_Export export) {
      final key = [export.library.uri, for (final combinator in export.combinators) _combinatorSource(combinator)].join(' ');
      exports.putIfAbsent(key, () => export);
    }

    for (final fragment in library.fragments) {
      for (final export in fragment.libraryExports) {
        final exportedLibrary = export.exportedLibrary;
        if (exportedLibrary == null) continue;
        if (!_isMergedLibrary(exportedLibrary)) {
          add((library: exportedLibrary, combinators: export.combinators));
        } else if (inProgress.contains(exportedLibrary.uri)) {
          isComplete = false;
        } else {
          final nested = _collectExternalExports(exportedLibrary, inProgress);
          isComplete = isComplete && nested.isComplete;
          for (final nestedExport in nested.exports) {
            add((library: nestedExport.library, combinators: [...nestedExport.combinators, ...export.combinators]));
          }
        }
      }
    }
    inProgress.remove(library.uri);
    final result = exports.values.toList();
    if (isComplete) _externalExportsCache[library.uri] = result;
    return (exports: result, isComplete: isComplete);
  }

  /// Third-party libraries exported by the public (non-`src`) merged libraries, which remain exported
  /// by the merged file.
  ///
  /// Only the names which the public library actually exports from the third-party library are exported,
  /// e.g., not the ones shadowed by its own declarations. Names exported from different declarations by
  /// multiple libraries are exported only by the first one.
  ///
  List<String> _publicExports(List<_MergedSource> sources, Map<String, analyzer_element.Element> exportedNames) {
    final exports = <String>[];
    final visitedLibraries = <Uri>{};
    for (final source in sources) {
      final library = source.result.libraryElement;
      final libPath = path.join(source.package.copyDirectory.path, 'lib');
      if (path.isWithin(path.join(libPath, 'src'), source.filePath) || !visitedLibraries.add(library.uri)) continue;
      for (final export in _externalExports(library)) {
        final hiddenNames = <String>[];
        final exportedElements = _exportedElements(export);
        for (final entry in exportedElements.entries) {
          final exported = _topLevelElement(library.exportNamespace.get2(entry.key));
          if (exported == null || _topLevelKey(exported) != _topLevelKey(entry.value)) {
            hiddenNames.add(entry.key);
            continue;
          }
          final existing = exportedNames.putIfAbsent(entry.key, () => entry.value);
          if (_topLevelKey(existing) != _topLevelKey(entry.value)) {
            print('Warning: "${entry.key}" is exported by multiple libraries, only the first one is exported.');
            hiddenNames.add(entry.key);
          }
        }
        if (hiddenNames.length == exportedElements.length) continue;
        final text = [
          "export '${export.library.uri}'",
          for (final combinator in export.combinators) _combinatorSource(combinator),
          if (hiddenNames.isNotEmpty) 'hide ${hiddenNames.join(', ')}',
        ].join(' ');
        if (!exports.contains('$text;')) exports.add('$text;');
      }
    }
    return exports;
  }

  /// Names used as for-in loop identifiers (e.g., `for (current in values)`), which can't be qualified,
  /// mapped to the keys of the top-level declarations they refer to.
  ///
  final _forInNames = <String, Set<String>>{};

  /// Top-level declarations referenced through removed import prefixes, where their names are shadowed.
  ///
  final _capturedTopLevelKeys = <String>{};

  /// Positions of the extension member invocations on the implicit `this`, which were made explicit.
  ///
  final _explicitExtensionOffsets = <(_MergedSource, int)>{};

  /// New names of the top-level declarations renamed to avoid clashes, mapped by their keys.
  ///
  final _topLevelRenames = <String, String>{};

  /// Unique identifier of an extension [element], including the unnamed ones.
  ///
  static String _extensionKey(analyzer_element.ExtensionElement element) {
    return '${element.library.uri}#${element.name ?? ''}@${element.firstFragment.offset}';
  }

  /// Names of the instance members declared by an extension [element].
  ///
  static Set<String> _extensionMemberNames(analyzer_element.ExtensionElement element) {
    return {
      for (final member in <analyzer_element.ExecutableElement>[...element.methods, ...element.getters, ...element.setters])
        if (!member.isStatic && member.name != null) member.name!,
    };
  }

  /// Makes the extension member invocations explicit where more extensions become visible once merged.
  ///
  /// An extension declared by another merged library, or imported by another merged file, may be more specific
  /// than the one an invocation originally resolved to, or make it ambiguous. Such invocations are rewritten to
  /// explicit extension overrides (e.g., `OnObject(value).describe()`), naming the unnamed extensions if needed.
  ///
  void _resolveExtensionClashes(List<_MergedSource> sources, List<_MergedImport> imports, Set<String> usedNames) {
    final visibleBySource = {
      for (final source in sources)
        source: {
          for (final extension in source.result.libraryFragment.accessibleExtensions) _extensionKey(extension): extension,
        },
    };
    final mergedScope = <String, analyzer_element.ExtensionElement>{
      for (final visible in visibleBySource.values) ...visible,
    };
    final declarations = <String, (_MergedSource, analyzer_ast.ExtensionDeclaration)>{
      for (final source in sources)
        for (final declaration in source.result.unit.declarations.whereType<analyzer_ast.ExtensionDeclaration>())
          if (declaration.declaredFragment?.element case final element?) _extensionKey(element): (source, declaration),
    };
    final overrideNames = <String, String?>{};
    final extensionPrefixes = <String, String>{};
    String uniqueName(String base) {
      var index = 0;
      while (usedNames.contains('$base$index')) {
        index++;
      }
      usedNames.add('$base$index');
      return '$base$index';
    }

    // Extension method invoking a closure with its receiver, used for the null-shorting chains.
    String? let;
    String letName() {
      if (let != null) return let!;
      final extension = uniqueName('_MergedLet');
      final method = uniqueName('_mergedLet');
      _additionalDeclarations.add(
        'extension $extension<T extends Object> on T {\n  R $method<R>(R Function(T value) apply) => apply(this);\n}',
      );
      return let = method;
    }

    String? overrideName(_MergedSource source, analyzer_element.ExtensionElement extension) {
      final key = _extensionKey(extension);
      if (!_isMergedLibrary(extension.library)) {
        // Third-party extensions are named through the imports of the library (including the ones of its parts),
        // with the prefix they are imported with, as it's named in the merged file.
        final name = extension.name;
        if (name == null) return null;
        final libraryImports = {
          ...source.result.libraryElement.firstFragment.libraryImports,
          ...source.result.libraryFragment.libraryImports,
        };
        for (final import in libraryImports) {
          final prefix = import.prefix?.name;
          // The namespaces of prefixed imports contain the prefixed names.
          final imported = import.namespace.get2(prefix == null ? name : '$prefix.$name');
          if (imported is! analyzer_element.ExtensionElement || _extensionKey(imported) != key) continue;
          if (prefix == null) {
            // A dedicated import prefix avoids clashes with other declarations of the same name.
            final uri = import.importedLibrary?.uri.toString();
            if (uri == null) return null;
            final dedicatedPrefix = extensionPrefixes.putIfAbsent(uri, () {
              final prefix = uniqueName('_merged_extensions');
              imports.add(
                _MergedImport(
                  source: null,
                  libraryKey: uri,
                  prefix: prefix,
                  isDeferred: false,
                  render: (prefix) => "import '$uri' as $prefix",
                ),
              );
              return prefix;
            });
            return '$dedicatedPrefix.$name';
          }
          final mergedPrefix = imports
              .where(
                (merged) => merged.source?.result.libraryElement.uri == source.result.libraryElement.uri && merged.originalPrefix == prefix,
              )
              .firstOrNull
              ?.prefix;
          if (mergedPrefix != null) return '$mergedPrefix.$name';
        }
        return null;
      }
      return overrideNames.putIfAbsent(key, () {
        final name = extension.name;
        if (name != null) return _topLevelRenames[_topLevelKey(extension)] ?? name;
        final declaration = declarations[key];
        if (declaration == null) return null;
        var index = 0;
        var newName = '_MergedExtension$index';
        while (usedNames.contains(newName)) {
          newName = '_MergedExtension${++index}';
        }
        usedNames.add(newName);
        final keyword = declaration.$2.extensionKeyword;
        declaration.$1.addEdit(keyword.end, keyword.end, ' $newName');
        return newName;
      });
    }

    for (final source in sources) {
      final visible = visibleBySource[source]!;
      final memberNames = {
        for (final entry in mergedScope.entries)
          if (!visible.containsKey(entry.key)) ..._extensionMemberNames(entry.value),
      };
      if (memberNames.isEmpty) continue;
      final visitor = _ExtensionOverrideVisitor(
        newValueName: () => uniqueName('_mergedValue'),
        source: source,
        memberNames: memberNames,
        overrideName: (extension) => overrideName(source, extension),
        explicitOffsets: _explicitExtensionOffsets,
      );
      source.result.unit.accept(visitor);
      if (visitor.nullAwareRewrites.isNotEmpty) visitor.applyNullAwareRewrites(letName());
    }
  }

  /// Unique identifier of a private class or extension member an [element] reference resolves to,
  /// or `null` if the element isn't such a member.
  ///
  static String? _privateMemberKey(analyzer_element.Element? element) {
    var base = element?.baseElement;
    if (base is analyzer_element.FieldFormalParameterElement) base = base.field;
    if (base is analyzer_element.PropertyAccessorElement) base = base.variable;
    if (base is! analyzer_element.FieldElement && base is! analyzer_element.MethodElement) return null;
    // Enum constants are static, they can't clash with the members of other libraries.
    if (base is analyzer_element.FieldElement && base.isEnumConstant) return null;
    final name = base!.name;
    if (name == null || !name.startsWith('_') || base.enclosingElement is! analyzer_element.InstanceElement) return null;
    return '${base.library!.uri}#$name';
  }

  /// Name tokens of the members declared by a class-like or extension [declaration].
  ///
  static Iterable<analyzer_token.Token> _memberNames(analyzer_ast.CompilationUnitMember declaration) sync* {
    final members = switch (declaration) {
      analyzer_ast.ClassDeclaration(:final members) ||
      analyzer_ast.MixinDeclaration(:final members) ||
      analyzer_ast.EnumDeclaration(:final members) ||
      analyzer_ast.ExtensionDeclaration(:final members) ||
      analyzer_ast.ExtensionTypeDeclaration(:final members) => members,
      _ => const <analyzer_ast.ClassMember>[],
    };
    if (declaration is analyzer_ast.ExtensionTypeDeclaration) yield declaration.representation.fieldName;
    for (final member in members) {
      if (member is analyzer_ast.MethodDeclaration) yield member.name;
      if (member is analyzer_ast.FieldDeclaration) {
        for (final variable in member.fields.variables) {
          yield variable.name;
        }
      }
    }
  }

  /// New names of the private members renamed to avoid clashes, mapped by their keys.
  ///
  final _privateRenames = <String, String>{};

  /// Name of a private member [name] of the [element] in the merged file.
  ///
  String _mergedMemberName(analyzer_element.InstanceElement element, String name) {
    return _privateRenames['${element.library.uri}#$name'] ?? name;
  }

  /// Names declared at the top level of the merged file, or provided by its imports (including prefixes).
  ///
  Set<String> _mergedScopeNames(List<_MergedSource> sources, List<_MergedImport> imports) {
    // The merged file imports `dart:core` without a prefix, if any of the files imports it explicitly.
    final coreLibrary = [
      for (final source in sources)
        for (final import in source.result.libraryFragment.libraryImports)
          if (import.importedLibrary?.uri.toString() == 'dart:core') import.importedLibrary!,
    ].firstOrNull;
    return {
      if (imports.any((import) => import.libraryKey == 'dart:core') && coreLibrary != null)
        for (final name in coreLibrary.exportNamespace.definedNames2.keys) name.replaceAll('=', ''),
      for (final import in imports) ?import.prefix,
      for (final source in sources) ...[
        for (final declaration in source.result.unit.declarations)
          for (final (element, _) in _declaredTopLevelElements(declaration)) _topLevelRenames[_topLevelKey(element)] ?? element.name!,
        for (final import in source.result.libraryFragment.libraryImports)
          if (import.prefix == null)
            for (final name in import.namespace.definedNames2.keys) name.replaceAll('=', ''),
      ],
    };
  }

  /// Qualifies the references to inherited instance members with `this`, if their names become visible
  /// at the top level of the merged file.
  ///
  /// An unqualified identifier resolves to a top-level declaration before an inherited member, so for example
  /// `position` in a subclass would start referring to a top-level `position()` function of another library.
  ///
  void _qualifyInheritedMembers(List<_MergedSource> sources, Set<String> scopeNames) {
    for (final source in sources) {
      source.result.unit.accept(_ImplicitThisVisitor(merger: this, source: source, scopeNames: scopeNames));
    }
  }

  /// Instance members of the [element] in the merged file, as `get:name`, `set:name` or `method:name` keys,
  /// only the concrete ones if [concrete].
  ///
  Iterable<String> _instanceMemberKeys(analyzer_element.InterfaceElement element, {required bool concrete}) sync* {
    bool include(bool isStatic, bool isSynthetic, bool isAbstract) => !isStatic && !isSynthetic && !(concrete && isAbstract);
    for (final field in element.fields) {
      if (!include(field.isStatic, field.isSynthetic, field.isAbstract) || field.name == null) continue;
      final name = _mergedMemberName(element, field.name!);
      yield 'get:$name';
      if (field.setter != null) yield 'set:$name';
    }
    for (final getter in element.getters) {
      if (include(getter.isStatic, getter.isSynthetic, getter.isAbstract) && getter.name != null) {
        yield 'get:${_mergedMemberName(element, getter.name!)}';
      }
    }
    for (final setter in element.setters) {
      if (include(setter.isStatic, setter.isSynthetic, setter.isAbstract) && setter.name != null) {
        yield 'set:${_mergedMemberName(element, setter.name!)}';
      }
    }
    for (final method in element.methods) {
      if (include(method.isStatic, false, method.isAbstract) && method.name != null) {
        yield 'method:${_mergedMemberName(element, method.name!)}';
      }
    }
  }

  /// Adapts the libraries opted into older language versions (e.g., `// @dart=2.19`) to the merged file.
  ///
  /// The merged file is a single library with a single language version, so the version comments are removed.
  /// The classes of libraries older than Dart 3.0 which are used as mixins are declared as `mixin class`,
  /// as required by Dart 3.0.
  ///
  void _adaptLanguageVersions(List<_MergedSource> sources, List<_MergedImport> imports, Set<String> usedNames) {
    final renamedPrefixLibraries = <Uri>{};
    final mergedVersion = _highestLowerBound(_configuration.packages.map((package) => package.pubspec.environment['sdk']));
    final wildcardVersion = pub_semver.Version(3, 7, 0);
    final reportedVersions = <String>{};
    final mixinKeys = <String>{
      for (final source in sources)
        for (final declaration in source.result.unit.declarations)
          for (final type in switch (declaration) {
            analyzer_ast.ClassDeclaration(:final withClause) ||
            analyzer_ast.EnumDeclaration(:final withClause) => withClause?.mixinTypes ?? const <analyzer_ast.NamedType>[],
            analyzer_ast.ClassTypeAlias(:final withClause) => withClause.mixinTypes,
            _ => const <analyzer_ast.NamedType>[],
          })
            if (_topLevelElement(type.element) case final element?) _topLevelKey(element),
    };
    for (final source in sources) {
      final versionToken = source.result.unit.languageVersionToken;
      if (versionToken != null) source.addEdit(versionToken.offset, versionToken.end, '');
      final version = source.result.libraryElement.languageVersion.effective;
      if (mergedVersion != null && version < mergedVersion && reportedVersions.add('${source.package.name} $version')) {
        print(
          'Warning: the ${source.package.name} package uses the language version $version, while the merged file uses '
          '$mergedVersion. Wildcard variables and class modifiers are adapted, other language changes are not.',
        );
      }
      if (mergedVersion != null && version < wildcardVersion && mergedVersion >= wildcardVersion) {
        // Before Dart 3.7, `_` declares a regular variable, which can't be referenced once it's a wildcard.
        var index = 0;
        String newName() {
          while (usedNames.contains('_wildcard$index')) {
            index++;
          }
          usedNames.add('_wildcard$index');
          return '_wildcard$index';
        }

        final visitor = _WildcardVisitor(source: source, newName: newName);
        source.result.unit.accept(visitor);
        visitor.isRenamingReferences = true;
        source.result.unit.accept(visitor);
        // Import prefixes named `_` would become wildcards as well.
        final library = source.result.libraryElement.uri;
        if (renamedPrefixLibraries.add(library) &&
            imports.any((import) => import.source?.result.libraryElement.uri == library && import.prefix == '_')) {
          _renamePrefix(imports, library, '_', newName());
        }
      }
      if (version.major >= 3) continue;
      if (version < pub_semver.Version(2, 12, 0)) {
        print('Warning: ${source.filePath} uses the language version $version without null safety, which can\'t be merged.');
      }
      for (final declaration in source.result.unit.declarations.whereType<analyzer_ast.ClassDeclaration>()) {
        final element = _topLevelElement(declaration.declaredFragment?.element);
        if (element != null && declaration.mixinKeyword == null && mixinKeys.contains(_topLevelKey(element))) {
          source.addEdit(declaration.classKeyword.offset, declaration.classKeyword.offset, 'mixin ');
        }
      }
    }
  }

  /// Declarations added to the merged file, e.g., the mixin providing the `noSuchMethod` forwarders.
  ///
  final _additionalDeclarations = <String>[];

  /// Implements the private members of other merged libraries, which classes, enums and mixin applications
  /// didn't have to implement before merging.
  ///
  /// A class doesn't have to implement the private members of an interface declared by another library,
  /// as they can't be accessed, and invoking them throws a [NoSuchMethodError] (even with a custom
  /// `noSuchMethod`). Once the libraries are merged, such members must be implemented, still throwing it:
  /// - getters are implemented with `late final Never` fields, which keep the private fields of the library
  ///   promotable (unlike explicit getters or `noSuchMethod` forwarders), or with `final Null` fields for classes
  ///   with constant constructors (which can't declare late fields), returning `null` instead,
  /// - methods and setters are implemented with explicit stubs, accepting any arguments,
  /// - mixin applications (which can't declare members) get the stubs from a dedicated mixin.
  ///
  void _implementPrivateMembers(List<_MergedSource> sources, Set<String> usedNames) {
    // Top-level declarations, which the stubs of the same names would shadow within the class bodies.
    final topLevelKeysByName = <String, List<String>>{};
    for (final source in sources) {
      for (final declaration in source.result.unit.declarations) {
        for (final (element, _) in _declaredTopLevelElements(declaration)) {
          topLevelKeysByName.putIfAbsent(element.name!, () => []).add(_topLevelKey(element));
        }
      }
    }

    String uniqueName(String base) {
      var index = 0;
      var name = base;
      while (usedNames.contains(name)) {
        name = '$base${++index}';
      }
      usedNames.add(name);
      return name;
    }

    for (final source in sources) {
      for (final declaration in source.result.unit.declarations) {
        final element = switch (declaration) {
          analyzer_ast.ClassDeclaration(:final declaredFragment) => declaredFragment?.element,
          analyzer_ast.EnumDeclaration(:final declaredFragment) => declaredFragment?.element,
          analyzer_ast.ClassTypeAlias(:final declaredFragment) => declaredFragment?.element,
          _ => null,
        };
        if (element == null || element is analyzer_element.ClassElement && element.isAbstract) continue;
        final supertypes = [
          for (final supertype in element.allSupertypes)
            if (_isMergedLibrary(supertype.element.library) && supertype.element.library.uri != element.library.uri) supertype.element,
        ];
        final required = <String>{
          for (final supertype in supertypes)
            for (final key in _instanceMemberKeys(supertype, concrete: false))
              if (key.substring(key.indexOf(':') + 1).startsWith('_')) key,
        };
        if (required.isEmpty) continue;
        // Concrete members of the superclass chain (excluding `Object`) and of the applied mixins.
        final concrete = <String>{};
        for (var type = element.thisType; !type.isDartCoreObject; type = type.element.supertype!) {
          for (final declarer in [type.element, for (final mixin in type.mixins) mixin.element]) {
            concrete.addAll(_instanceMemberKeys(declarer, concrete: true));
          }
          if (type.element.supertype == null) break;
        }
        final missing = required.difference(concrete);
        if (missing.isEmpty) continue;

        // Mixin applications with constant superclass constructors are converted to classes, as the stubs
        // can't be provided by a mixin without making their constructors non-constant.
        final superConstructors = [
          for (final constructor in element.supertype?.element.constructors ?? const <analyzer_element.ConstructorElement>[])
            if (!constructor.isFactory && !(constructor.name?.startsWith('_') == true && constructor.library.uri != element.library.uri))
              constructor,
        ];
        final isConvertedAlias = declaration is analyzer_ast.ClassTypeAlias && superConstructors.any((constructor) => constructor.isConst);
        final isAlias = declaration is analyzer_ast.ClassTypeAlias && !isConvertedAlias;
        final override = isAlias ? '' : '@override\n  ';
        // Late fields can't be declared by enums, and by classes with constant constructors (for mixin
        // applications, by the superclass).
        final constructors = declaration is analyzer_ast.ClassTypeAlias ? superConstructors : element.constructors;
        final canBeLate =
            declaration is! analyzer_ast.EnumDeclaration &&
            !constructors.any((constructor) => constructor.isConst && !constructor.isFactory);

        bool isNullableGetter(String name) {
          for (final supertype in supertypes) {
            for (final field in supertype.fields) {
              if (field.name != null && _mergedMemberName(supertype, field.name!) == name) {
                if (source.result.typeSystem.isNullable(field.type)) return true;
              }
            }
            for (final getter in supertype.getters) {
              if (getter.name != null && _mergedMemberName(supertype, getter.name!) == name) {
                if (source.result.typeSystem.isNullable(getter.returnType)) return true;
              }
            }
          }
          return false;
        }

        analyzer_element.MethodElement? findMethod(String name) {
          for (final supertype in supertypes) {
            for (final method in supertype.methods) {
              if (method.name != null && _mergedMemberName(supertype, method.name!) == name) return method;
            }
          }
          return null;
        }

        final stubs = StringBuffer();
        var needsNoSuchMethod = false;
        for (final key in missing) {
          final name = key.substring(key.indexOf(':') + 1);
          _capturedTopLevelKeys.addAll(topLevelKeysByName[name] ?? const []);
          switch (key.substring(0, key.indexOf(':'))) {
            case 'get':
              final error = 'throw NoSuchMethodError.withInvocation(this, Invocation.getter(#$name))';
              if (canBeLate) {
                stubs.write('\n  ${override}late final Never $name = $error;\n');
              } else if (isNullableGetter(name)) {
                stubs.write('\n  ${override}final Null $name = null;\n');
              } else {
                print(
                  'Warning: ${element.name} implements the private "$name" getter of another merged library with a getter, '
                  'which prevents the promotion of private "$name" fields in the merged file.',
                );
                stubs.write('\n  ${override}Never get $name => $error;\n');
              }
            case 'set':
              stubs.write(
                '\n  ${override}set $name(Object? value) => '
                'throw NoSuchMethodError.withInvocation(this, Invocation.setter(#$name, value));\n',
              );
            case 'method':
              final method = findMethod(name);
              // Type parameters with bounds can't be declared without referencing their bound types.
              if (method == null || method.typeParameters.any((parameter) => parameter.bound != null)) {
                needsNoSuchMethod = true;
                continue;
              }
              final typeParameters = [for (var index = 0; index < method.typeParameters.length; index++) 'T$index'];
              final positional = [
                for (final (index, parameter) in method.formalParameters.indexed)
                  if (parameter.isRequiredPositional) 'Object? p$index',
              ];
              final optional = [
                for (final (index, parameter) in method.formalParameters.indexed)
                  if (parameter.isOptionalPositional) 'Object? p$index',
              ];
              final named = [
                for (final parameter in method.formalParameters)
                  if (parameter.isNamed) 'Object? ${parameter.name}',
              ];
              final parameters = [
                ...positional,
                if (optional.isNotEmpty) '[${optional.join(', ')}]',
                if (named.isNotEmpty) '{${named.join(', ')}}',
              ].join(', ');
              stubs.write(
                '\n  ${override}Never $name${typeParameters.isEmpty ? '' : '<${typeParameters.join(', ')}>'}($parameters) => '
                'throw NoSuchMethodError.withInvocation(this, Invocation.method(#$name, const []));\n',
              );
          }
        }
        if (needsNoSuchMethod && !concrete.contains('method:noSuchMethod')) {
          stubs.write('\n  ${override}dynamic noSuchMethod(Invocation invocation) => super.noSuchMethod(invocation);\n');
        }
        switch (declaration) {
          case analyzer_ast.ClassDeclaration(:final rightBracket):
            source.addEdit(rightBracket.offset, rightBracket.offset, stubs.toString());
          case analyzer_ast.EnumDeclaration():
            _addEnumMembers(source, declaration, stubs.toString());
          case analyzer_ast.ClassTypeAlias(:final equals, :final semicolon, :final name) when isConvertedAlias:
            // `class A = S with M;` is declared as `class A extends S with M { ... }`, forwarding the superclass
            // constructors with super parameters.
            final mixinsHaveFields = element.mixins.any(
              (mixin) => mixin.element.fields.any((field) => !field.isStatic && !field.isSynthetic),
            );
            final forwarders = StringBuffer();
            for (final constructor in superConstructors) {
              final parameters = constructor.formalParameters;
              final isUnnamed = constructor.name == null || constructor.name == 'new' || constructor.name!.isEmpty;
              final parameterList = [
                for (final (index, parameter) in parameters.indexed)
                  if (parameter.isRequiredPositional) 'super.p$index',
                if (parameters.any((parameter) => parameter.isOptionalPositional))
                  '[${[
                    for (final (index, parameter) in parameters.indexed)
                      if (parameter.isOptionalPositional) 'super.p$index',
                  ].join(', ')}]',
                if (parameters.any((parameter) => parameter.isNamed))
                  '{${[
                    for (final parameter in parameters)
                      if (parameter.isNamed) '${parameter.isRequiredNamed ? 'required ' : ''}super.${parameter.name}',
                  ].join(', ')}}',
              ].join(', ');
              forwarders.write(
                '\n  ${constructor.isConst && !mixinsHaveFields ? 'const ' : ''}'
                '${isUnnamed ? name.lexeme : '${name.lexeme}.${constructor.name}'}($parameterList)'
                '${isUnnamed ? '' : ' : super.${constructor.name}()'};\n',
              );
            }
            source.addEdit(equals.offset, equals.end, 'extends');
            source.addEdit(semicolon.offset, semicolon.end, ' {$forwarders$stubs}');
          case analyzer_ast.ClassTypeAlias(:final withClause):
            final mixinName = uniqueName('_MergedStubs');
            _additionalDeclarations.add('mixin $mixinName {$stubs}');
            source.addEdit(withClause.end, withClause.end, ', $mixinName');
          default:
        }
      }
    }
  }

  /// Renames the private members declared under the same names by multiple merged libraries.
  ///
  /// Private members of different libraries are unrelated, but once the libraries are merged, they would
  /// override or conflict with one another (e.g., `Child._init` would start overriding `Base._init`).
  ///
  void _resolvePrivateMemberClashes(List<_MergedSource> sources, Set<String> usedNames) {
    final librariesByName = <String, Set<Uri>>{};
    for (final source in sources) {
      for (final declaration in source.result.unit.declarations) {
        for (final name in _memberNames(declaration)) {
          if (name.lexeme.startsWith('_')) {
            librariesByName.putIfAbsent(name.lexeme, () => {}).add(source.result.libraryElement.uri);
          }
        }
      }
    }
    final renames = _privateRenames;
    for (final entry in librariesByName.entries) {
      for (final library in entry.value.skip(1)) {
        var index = 1;
        var newName = '${entry.key}_$index';
        while (usedNames.contains(newName)) {
          newName = '${entry.key}_${++index}';
        }
        usedNames.add(newName);
        renames['$library#${entry.key}'] = newName;
        print('Renamed the private "${entry.key}" members of $library to "$newName" to avoid clashes between the merged libraries.');
      }
    }
    if (renames.isEmpty) return;
    for (final source in sources) {
      source.result.unit.accept(_PrivateMemberVisitor(source: source, renames: renames));
    }
  }

  /// Renames the import prefixes shared by merged files for different libraries.
  ///
  /// A prefix may be shared by multiple files only if it refers to the same libraries in all of them.
  ///
  void _resolvePrefixClashes(List<_MergedSource> sources, List<_MergedImport> imports, Set<String> usedNames) {
    // Third-party names imported without a prefix by any of the merged files, which a prefix would shadow.
    final importedNames = {
      for (final source in sources)
        for (final import in source.result.libraryFragment.libraryImports)
          if (import.prefix == null)
            for (final entry in import.namespace.definedNames2.entries)
              if (!_isMergedLibrary(entry.value.library)) entry.key.replaceAll('=', ''),
    };
    // Prefixes are declared by libraries, and used by all of their files (including the parts).
    final importsByLibraryPrefix = <(Uri, String), List<_MergedImport>>{};
    for (final import in imports) {
      final source = import.source, prefix = import.prefix;
      if (source == null || prefix == null) continue;
      importsByLibraryPrefix.putIfAbsent((source.result.libraryElement.uri, prefix), () => []).add(import);
    }
    // Libraries grouped by the prefix name and by the imported libraries it refers to.
    final bindings = <String, Map<String, List<Uri>>>{};
    for (final entry in importsByLibraryPrefix.entries) {
      final binding = ([
        for (final import in entry.value) import.isDeferred ? 'deferred ${import.text}' : import.libraryKey,
      ]..sort()).toSet().join('\n');
      bindings.putIfAbsent(entry.key.$2, () => {}).putIfAbsent(binding, () => []).add(entry.key.$1);
    }
    for (final entry in bindings.entries) {
      final prefix = entry.key;
      final isDeferred = entry.value.keys.any((binding) => binding.startsWith('deferred '));
      final groups = entry.value.values.toList();
      // Deferred prefixes can't be shared with any other import, even of the same library.
      final separateGroups = isDeferred
          ? [
              for (final group in groups)
                for (final library in group) [library],
            ]
          : groups;
      // A prefix clashing with an imported name is renamed for all of the files.
      final renamedGroups = importedNames.contains(prefix) ? separateGroups : separateGroups.skip(1);
      for (final group in renamedGroups) {
        var index = 1;
        var newPrefix = '${prefix}_$index';
        while (usedNames.contains(newPrefix)) {
          newPrefix = '${prefix}_${++index}';
        }
        usedNames.add(newPrefix);
        for (final library in group) {
          _renamePrefix(imports, library, prefix, newPrefix);
        }
        print('Renamed the "$prefix" import prefix to "$newPrefix" to avoid a clash between the merged files.');
      }
    }
  }

  /// Renames the [prefix] of the imports of the [library] to [newPrefix], along with its usages in all files.
  ///
  void _renamePrefix(List<_MergedImport> imports, Uri library, String prefix, String newPrefix) {
    for (final import in imports) {
      if (import.source?.result.libraryElement.uri == library && import.prefix == prefix) import.prefix = newPrefix;
    }
    for (final usage in _prefixUsages) {
      if (usage.source.result.libraryElement.uri == library && usage.token.lexeme == prefix) {
        usage.source.addEdit(usage.token.offset, usage.token.end, newPrefix);
      }
    }
  }

  /// Returns the end of a comment following the [offset] on the same line, or the [offset] itself.
  ///
  static int _endOfTrailingComment(String contents, int offset) {
    final lineEnd = contents.indexOf('\n', offset);
    final rest = contents.substring(offset, lineEnd == -1 ? contents.length : lineEnd);
    return RegExp(r'^[ \t]*//').hasMatch(rest) ? offset + rest.trimRight().length : offset;
  }

  /// Finds the top-level names which would clash once the libraries are merged, and renames them.
  ///
  /// First-party top-level declarations are renamed if the same name is declared by multiple
  /// libraries, if the name refers to a different, third-party declaration in any of the libraries,
  /// or if the name is used as an import prefix.
  /// Third-party references with ambiguous names are prefixed with a dedicated import.
  ///
  void _resolveNameClashes(
    List<_MergedSource> sources,
    List<_TopLevelReference> references,
    List<_MergedImport> imports,
    Set<String> usedNames,
    Map<String, analyzer_element.Element> exportedNames,
  ) {
    final prefixes = {for (final import in imports) ?import.prefix};
    // First-party top-level declarations, in the order of declaration. The entry point files are ordered first,
    // so that their `main` function keeps its name, if multiple libraries declare one.
    final declarations = <String, analyzer_element.Element>{};
    final orderedSources = [
      ...sources.where((source) => path.basename(source.filePath) == 'main.dart'),
      ...sources.where((source) => path.basename(source.filePath) != 'main.dart'),
    ];
    for (final source in orderedSources) {
      for (final declaration in source.result.unit.declarations) {
        for (final (element, _) in _declaredTopLevelElements(declaration)) {
          declarations.putIfAbsent(_topLevelKey(element), () => element);
        }
      }
    }
    final externalReferencesByName = <String, Map<String, List<_TopLevelReference>>>{};
    for (final reference in references) {
      if (_isMergedLibrary(reference.element.library)) continue;
      externalReferencesByName
          .putIfAbsent(reference.element.name!, () => {})
          .putIfAbsent(_topLevelKey(reference.element), () => [])
          .add(reference);
    }

    final renames = _topLevelRenames;
    final declaredNames = <String>{};
    for (final entry in declarations.entries) {
      final name = entry.value.name!;
      final isExportedElsewhere = exportedNames.containsKey(name) && !_isMergedLibrary(exportedNames[name]!.library);
      // A for-in loop identifier referring to a member would be captured by a top-level declaration.
      final forInKeys = _forInNames[name];
      final capturesForIn = forInKeys != null && !forInKeys.contains(entry.key);
      if (declaredNames.add(name) &&
          !externalReferencesByName.containsKey(name) &&
          !prefixes.contains(name) &&
          !isExportedElsewhere &&
          !capturesForIn &&
          !_capturedTopLevelKeys.contains(entry.key)) {
        continue;
      }
      var index = 1;
      var newName = '${name}_$index';
      while (usedNames.contains(newName)) {
        newName = '${name}_${++index}';
      }
      usedNames.add(newName);
      renames[entry.key] = newName;
      print('Renamed the top-level declaration "$name" of ${entry.value.library!.uri} to "$newName" to avoid a name clash.');
    }

    for (final source in sources) {
      for (final declaration in source.result.unit.declarations) {
        for (final (element, token) in _declaredTopLevelElements(declaration)) {
          final newName = renames[_topLevelKey(element)];
          if (newName == null) continue;
          source.addEdit(token.offset, token.end, newName);
          // The string representation of enum values includes the enum name, which is kept.
          if (declaration is analyzer_ast.EnumDeclaration && element is analyzer_element.EnumElement && !_declaresToString(element)) {
            // `EnumName` is applied explicitly, as the enum may declare its own `name` getter.
            _addEnumMembers(
              source,
              declaration,
              "\n  @override\n  String toString() => '${element.name}.\${EnumName(this).name}';\n",
            );
          }
        }
      }
    }
    for (final reference in references) {
      final newName = renames[_topLevelKey(reference.element)];
      if (newName != null) reference.source.addEdit(reference.offset, reference.end, newName);
    }

    // Third-party declarations provided under the [name] by the unprefixed imports of any of the merged files.
    // Once merged, all of them are visible to all of the files, regardless of the combinators of other files.
    Set<String> providers(String name) => {
      for (final source in sources)
        for (final import in source.result.libraryFragment.libraryImports)
          if (import.prefix == null)
            if (_topLevelElement(import.namespace.get2(name)) case final element?)
              if (!_isMergedLibrary(element.library)) _topLevelKey(element),
    };

    // Third-party names which are ambiguous in the merged file are accessed with dedicated import prefixes.
    var prefixIndex = 0;
    for (final entry in externalReferencesByName.entries) {
      if (entry.value.length < 2 && providers(entry.key).length < 2) continue;
      for (final elementReferences in entry.value.values) {
        final reference = elementReferences.first;
        final importUri = _findImportUri(reference.source, reference.element);
        if (importUri == null) {
          print('Warning: unable to disambiguate the "${entry.key}" name in the merged file.');
          continue;
        }
        String prefix;
        do {
          prefix = '_merged_import_${prefixIndex++}';
        } while (usedNames.contains(prefix));
        usedNames.add(prefix);
        imports.add(
          _MergedImport(
            source: null,
            libraryKey: importUri,
            prefix: prefix,
            isDeferred: false,
            render: (prefix) => "import '$importUri' as $prefix",
          ),
        );
        for (final elementReference in elementReferences) {
          if (elementReference.isSimpleInterpolation) {
            // `$name` is converted to `${prefix.name}`.
            elementReference.source.addEdit(elementReference.offset, elementReference.offset, '{$prefix.', priority: 0);
            elementReference.source.addEdit(elementReference.end, elementReference.end, '}');
          } else {
            elementReference.source.addEdit(elementReference.offset, elementReference.offset, '$prefix.');
          }
        }
      }
    }
  }

  /// Whether an enum [element] declares or inherits (e.g., from a mixin) its own `toString` method.
  ///
  static bool _declaresToString(analyzer_element.EnumElement element) {
    return [element, for (final mixin in element.mixins) mixin.element].any(
      (declarer) => declarer.methods.any((method) => method.name == 'toString'),
    );
  }

  /// Adds the [members] to an enum [declaration], separating them from the values if needed.
  ///
  static void _addEnumMembers(_MergedSource source, analyzer_ast.EnumDeclaration declaration, String members) {
    final offset = declaration.rightBracket.offset;
    if (declaration.semicolon == null) source.addEdit(offset, offset, ';', priority: 0);
    source.addEdit(offset, offset, members);
  }

  /// Returns the URI of an import through which the [element] is referenced by the [source].
  ///
  String? _findImportUri(_MergedSource source, analyzer_element.Element element) {
    final libraryFragment = source.result.libraryElement.firstFragment;
    for (final import in libraryFragment.libraryImports) {
      if (import.prefix != null) continue;
      final importedElement = _topLevelElement(import.namespace.get2(element.name!));
      if (importedElement == null || _topLevelKey(importedElement) != _topLevelKey(element)) continue;
      final importedLibrary = import.importedLibrary;
      if (importedLibrary == null) continue;
      if (!_isMergedLibrary(importedLibrary)) return importedLibrary.uri.toString();
      // The element is re-exported by a merged library, it's imported from the exporting third-party library.
      for (final export in _externalExports(importedLibrary)) {
        final exportedElement = _exportedElements(export)[element.name];
        if (exportedElement != null && _topLevelKey(exportedElement) == _topLevelKey(element)) {
          return export.library.uri.toString();
        }
      }
    }
    return null;
  }

  /// Top-level elements declared by the [declaration], along with their name tokens.
  ///
  static Iterable<(analyzer_element.Element, analyzer_token.Token)> _declaredTopLevelElements(
    analyzer_ast.CompilationUnitMember declaration,
  ) sync* {
    if (declaration is analyzer_ast.TopLevelVariableDeclaration) {
      for (final variable in declaration.variables.variables) {
        final element = _topLevelElement(variable.declaredFragment?.element);
        if (element != null) yield (element, variable.name);
      }
      return;
    }
    final element = _topLevelElement(declaration.declaredFragment?.element);
    if (element == null) return;
    final token = switch (declaration) {
      analyzer_ast.NamedCompilationUnitMember(:final name) => name,
      analyzer_ast.ExtensionDeclaration(:final name) => name,
      _ => null,
    };
    if (token != null) yield (element, token);
  }

  /// Applies the recorded edits to the [source] contents.
  ///
  static String _applyEdits(_MergedSource source) {
    final contents = source.result.content;
    final edits = [...source.edits]
      ..sort(
        (a, b) => a.offset != b.offset
            ? a.offset.compareTo(b.offset)
            : a.priority != b.priority
            ? a.priority.compareTo(b.priority)
            : a.end != b.end
            ? a.end.compareTo(b.end)
            : a.order.compareTo(b.order),
      );
    final buffer = StringBuffer();
    var position = 0;
    var isRemoval = false;
    for (final edit in edits) {
      // Edits are applied in a single pass, in the order of their offsets, and must not overlap,
      // except for the edits within removed code (e.g., references in the comments of removed directives).
      if (edit.offset < position) {
        if (isRemoval && edit.end <= position) continue;
        throw StateError('Overlapping merge edits in ${source.filePath} at offset ${edit.offset}.');
      }
      isRemoval = edit.text.isEmpty && edit.end > edit.offset;
      buffer
        ..write(contents.substring(position, edit.offset))
        ..write(edit.text);
      position = edit.end;
    }
    buffer.write(contents.substring(position));
    return buffer.toString().trim();
  }

  /// Converts a [dependency] declared by the [package] to a `pubspec.yaml` value.
  ///
  Object? _dependencyToYamlNode(
    SourcePackage package,
    pubspec_parse.Dependency dependency,
  ) {
    return switch (dependency) {
      pubspec_parse.HostedDependency(:final hosted, :final version) =>
        hosted?.url == null
            ? version.toString()
            : {
                'hosted': {
                  if (hosted!.declaredName != null) 'name': hosted.declaredName,
                  'url': hosted.url.toString(),
                },
                'version': version.toString(),
              },
      pubspec_parse.PathDependency(path: final dependencyPath) => {
        'path': _configuration.resolveDependencyPath(
          baseDirectory: package.sourceDirectory.path,
          dependencyPath: dependencyPath,
          preferCopies: false,
        ),
      },
      pubspec_parse.GitDependency(:final url, :final ref, path: final gitPath) => {
        'git': {
          'url': url.toString(),
          if (ref != null) 'ref': ref,
          if (gitPath != null) 'path': gitPath,
        },
      },
      pubspec_parse.SdkDependency(:final sdk, :final version) => {
        'sdk': sdk,
        if (version != pub_semver.VersionConstraint.any) 'version': version.toString(),
      },
    };
  }

  /// Returns the highest lower bound of the [constraints], or `null` if none of them has a lower bound.
  ///
  static pub_semver.Version? _highestLowerBound(Iterable<pub_semver.VersionConstraint?> constraints) {
    pub_semver.Version? minimum;
    for (final constraint in constraints) {
      if (constraint is pub_semver.VersionRange) {
        final min = constraint.min;
        if (min != null && (minimum == null || min > minimum)) minimum = min;
      }
    }
    return minimum;
  }

  /// Copies an asset (file or directory) declared by the [package] to the output directory.
  ///
  /// Returns `false` if the asset can't be included with the merged project.
  ///
  bool _copyAsset(SourcePackage package, String assetPath) {
    final sourcePath = path.join(package.sourceDirectory.path, assetPath);
    final outputPath = _configuration.outputDirectory.path;
    final destinationPath = path.normalize(path.join(outputPath, assetPath));
    if (!path.isWithin(outputPath, destinationPath)) {
      print('Warning: asset "$assetPath" of the ${package.name} package is placed outside of the package, it is not included.');
      return false;
    }
    final type = dart_io.FileSystemEntity.typeSync(sourcePath);
    if (type == dart_io.FileSystemEntityType.file) {
      if (assetPath.endsWith('.dart')) {
        print('Warning: Dart asset "$assetPath" of the ${package.name} package is not included, as it is not obfuscated.');
        return false;
      }
      dart_io.File(destinationPath).parent.createSync(recursive: true);
      dart_io.File(sourcePath).copySync(destinationPath);
    } else if (type == dart_io.FileSystemEntityType.directory) {
      for (final entity in dart_io.Directory(sourcePath).listSync(recursive: true)) {
        // Dart sources declared as assets (e.g., `lib/`) would leak the original code next to the merged file.
        if (entity is! dart_io.File || entity.path.endsWith('.dart')) continue;
        final target = path.join(destinationPath, path.relative(entity.path, from: sourcePath));
        dart_io.File(target).parent.createSync(recursive: true);
        entity.copySync(target);
      }
    } else {
      print('Warning: asset "$assetPath" of the ${package.name} package was not found, it is not included.');
      return false;
    }
    return true;
  }

  /// Copies the non-Dart files of the `lib` directories (e.g., resources resolved with `package:` URIs)
  /// next to the merged file.
  ///
  void _copyLibraryResources() {
    final outputLib = path.join(_configuration.outputDirectory.path, 'lib');
    final reportedPackages = <String>{};
    for (final package in _configuration.packages) {
      final libDirectory = dart_io.Directory(path.join(package.copyDirectory.path, 'lib'));
      if (!libDirectory.existsSync()) continue;
      for (final entity in libDirectory.listSync(recursive: true, followLinks: false)) {
        if (entity is! dart_io.File || entity.path.endsWith('.dart')) continue;
        if (package.nestedPackageDirectories.any((directory) => path.isWithin(directory, entity.path))) continue;
        final target = dart_io.File(path.join(outputLib, path.relative(entity.path, from: libDirectory.path)));
        if (path.equals(target.path, _configuration.outputMergedFile.path)) continue;
        if (target.existsSync()) {
          print('Warning: the "${path.relative(target.path, from: outputLib)}" resource is provided by multiple packages.');
        }
        target.parent.createSync(recursive: true);
        entity.copySync(target.path);
        if (_configuration.packages.length > 1 && reportedPackages.add(package.name)) {
          print(
            'Warning: the resources of the ${package.name} package are included with the merged package, '
            'references to them with `package:${package.name}/` URIs must be updated.',
          );
        }
      }
    }
  }

  /// Merges the `flutter` sections of the source packages, copying the declared assets and fonts.
  ///
  Map<String, Object?>? _mergeFlutterConfiguration() {
    final merged = <String, Object?>{};
    final assets = <Object?>[];
    final fonts = <Object?>[];
    for (final package in _configuration.packages) {
      final configuration = package.pubspec.flutter;
      if (configuration == null) continue;
      if (configuration['uses-material-design'] == true) merged['uses-material-design'] = true;
      if (configuration['generate'] == true) {
        merged['generate'] = true;
        print('Warning: "flutter: generate: true" (e.g., localizations) is not supported by the merged project.');
      }
      final packageAssets = configuration['assets'];
      if (packageAssets is List) {
        for (final asset in packageAssets) {
          final assetPath = asset is Map ? asset['path'] : asset;
          if (assetPath is! String || !_copyAsset(package, assetPath)) continue;
          if (!assets.any((existing) => existing.toString() == asset.toString())) assets.add(asset);
        }
      }
      final packageFonts = configuration['fonts'];
      if (packageFonts is List) {
        for (final family in packageFonts) {
          final familyFonts = family is Map ? family['fonts'] : null;
          if (familyFonts is! List) continue;
          var included = true;
          for (final font in familyFonts) {
            final asset = font is Map ? font['asset'] : null;
            if (asset is! String || !_copyAsset(package, asset)) included = false;
          }
          if (included) fonts.add(family);
        }
      }
    }
    if (assets.isNotEmpty) merged['assets'] = assets;
    if (fonts.isNotEmpty) merged['fonts'] = fonts;
    return merged.isEmpty ? null : merged;
  }

  /// Generates a new `pubspec.yaml` file from the source package specifications.
  ///
  void _generateMergedPubspecFile(Set<String> importedPackages) {
    final packages = _configuration.packages;
    final sourcePackageNames = _configuration.sourcePackages.toSet();
    Map<String, Object?> mergeDependencies(Map<String, pubspec_parse.Dependency> Function(pubspec_parse.Pubspec) section) {
      final result = <String, Object?>{};
      for (final package in packages) {
        for (final entry in section(package.pubspec).entries) {
          if (sourcePackageNames.contains(entry.key)) continue;
          final node = _dependencyToYamlNode(package, entry.value);
          final existing = result[entry.key];
          if (!result.containsKey(entry.key)) {
            result[entry.key] = node;
          } else if (dart_convert.jsonEncode(existing) != dart_convert.jsonEncode(node)) {
            // Hosted version constraints are intersected, other conflicting declarations are reported.
            final intersection = existing is String && node is String
                ? pub_semver.VersionConstraint.parse(existing).intersect(pub_semver.VersionConstraint.parse(node))
                : null;
            if (intersection != null && !intersection.isEmpty) {
              result[entry.key] = intersection.toString();
            } else {
              print(
                'Warning: conflicting declarations of the "${entry.key}" dependency (${dart_convert.jsonEncode(existing)} and '
                '${dart_convert.jsonEncode(node)}), the first one is used.',
              );
            }
          }
        }
      }
      return result;
    }

    final sdkMinimum = _highestLowerBound(packages.map((package) => package.pubspec.environment['sdk']));
    final environment = <String, Object?>{
      'sdk': sdkMinimum == null ? '^3.0.0' : '>=$sdkMinimum <${dart_math.max(4, sdkMinimum.major + 1)}.0.0',
    };
    final flutterMinimum = _highestLowerBound(packages.map((package) => package.pubspec.environment['flutter']));
    if (flutterMinimum != null) environment['flutter'] = '>=$flutterMinimum';
    final dependencies = mergeDependencies((pubspec) => pubspec.dependencies);
    // Development dependencies imported by the merged code are regular dependencies of the merged package.
    final importedDevDependencies = mergeDependencies((pubspec) => pubspec.devDependencies)
      ..removeWhere((name, _) => !importedPackages.contains(name) || dependencies.containsKey(name));
    for (final name in importedDevDependencies.keys) {
      print('Warning: the development dependency "$name" is imported by the merged code, it is added as a dependency.');
    }
    dependencies.addAll(importedDevDependencies);
    // Development dependencies are not included, as the merged package contains no tests or tools, and they may
    // depend on the merged package itself (e.g., `test` on `args`), which would conflict with it.
    final dependencyOverrides = mergeDependencies((pubspec) => pubspec.dependencyOverrides);
    // Local overrides (e.g., generated by melos) take precedence over the ones of the pubspec files.
    for (final package in packages) {
      final overridesFile = dart_io.File(path.join(package.sourceDirectory.path, 'pubspec_overrides.yaml'));
      if (!overridesFile.existsSync()) continue;
      final overrides = pubspec_parse.Pubspec.parse(
        'name: overrides\n${overridesFile.readAsStringSync()}',
        lenient: true,
      ).dependencyOverrides;
      for (final entry in overrides.entries) {
        if (!sourcePackageNames.contains(entry.key)) {
          dependencyOverrides[entry.key] = _dependencyToYamlNode(package, entry.value);
        }
      }
    }
    final flutter = _mergeFlutterConfiguration();

    // A single package keeps its name, so that references to its own assets (e.g., `package: 'name'`) remain valid.
    final name = packages.length == 1 ? packages.single.name : 'merged_app';
    final version = packages.length == 1 ? packages.single.pubspec.version?.toString() ?? '1.0.0+1' : '1.0.0+1';
    if (packages.length > 1 && flutter != null) {
      print(
        'Warning: the assets of the merged packages are included with the "$name" package, '
        'references to them with the original package names (e.g., `package: \'name\'`) must be updated.',
      );
    }
    final editor = yaml_edit.YamlEditor('');
    editor.update([], {
      'name': name,
      'description': 'A new merged application.',
      'version': version,
      'publish_to': 'none',
      'environment': environment,
      if (dependencies.isNotEmpty) 'dependencies': dependencies,
      if (dependencyOverrides.isNotEmpty) 'dependency_overrides': dependencyOverrides,
      'flutter': ?flutter,
    });
    _configuration.mergedPubspecFile.writeAsStringSync('${editor.toString().trim()}\n');
  }

  /// Outputs all of the [Configuration.packages] `lib` contents to a single file.
  ///
  /// Returns `false` if the merged output could not be generated as valid Dart code.
  ///
  Future<bool> generateMergedProject() async {
    final collection = analyzer_context.AnalysisContextCollection(
      includedPaths: [for (final package in _configuration.packages) package.copyDirectory.path],
    );
    final sources = await _resolveSources(collection);
    final imports = <_MergedImport>[];
    final references = _prepareSources(sources, imports);
    final usedNames = {..._collector.usedIdentifiers};
    _resolvePrefixClashes(sources, imports, usedNames);
    _resolvePrivateMemberClashes(sources, usedNames);
    _implementPrivateMembers(sources, usedNames);
    _adaptLanguageVersions(sources, imports, usedNames);
    final exportedNames = <String, analyzer_element.Element>{};
    final exports = _publicExports(sources, exportedNames);
    _resolveNameClashes(sources, references, imports, usedNames, exportedNames);
    _resolveExtensionClashes(sources, imports, usedNames);
    _qualifyInheritedMembers(sources, _mergedScopeNames(sources, imports));
    await collection.dispose();

    final fileBuffer = StringBuffer();
    final importTexts = <String>{
      // An explicit import of `dart:core` (e.g., `import 'dart:core' as $core;` in generated code)
      // disables its implicit import, which the other merged libraries rely on.
      if (imports.any((import) => import.libraryKey == 'dart:core')) "import 'dart:core';",
      for (final import in imports) '${import.text};',
    };
    for (final directive in [...importTexts, ...exports]) {
      fileBuffer.writeln(directive);
    }
    fileBuffer.writeln();
    for (final source in sources) {
      final contents = _applyEdits(source);
      if (contents.isEmpty) continue;
      fileBuffer
        ..writeln(contents)
        ..writeln();
    }
    for (final declaration in _additionalDeclarations) {
      fileBuffer
        ..writeln(declaration)
        ..writeln();
    }

    // Format available output data.
    var success = true;
    var formattedCode = fileBuffer.toString();
    try {
      formattedCode = _configuration.formatter.format(formattedCode);
    } catch (e) {
      success = false;
      print('Error: the merged code could not be formatted, as it is not valid Dart code:\n$e');
    }
    await _configuration.outputMergedFile.writeAsString(formattedCode);

    _copyLibraryResources();

    // Record the merged `pubspec.yaml` file and run package setup.
    _generateMergedPubspecFile({
      for (final directive in [...importTexts, ...exports])
        if (RegExp(r'package:([A-Za-z0-9_]+)/').firstMatch(directive)?.group(1) case final name?) name,
    });
    try {
      await Configuration.runPubGet(
        directory: _configuration.outputDirectory,
        flutter: _configuration.packages.any((package) => package.usesFlutter),
      );
    } on ConfigurationException catch (e) {
      print('Warning: dependencies of the merged project could not be resolved:\n$e');
    }
    return success;
  }
}

/// Collects the references to top-level declarations, and removes the first-party import prefixes.
///
class _MergeReferenceVisitor extends analyzer_visitor.RecursiveAstVisitor<void> {
  _MergeReferenceVisitor({
    required this.merger,
    required this.source,
    required this.references,
  });

  final ProjectMerger merger;

  final _MergedSource source;

  final List<_TopLevelReference> references;

  @override
  void visitImportDirective(analyzer_ast.ImportDirective node) {}

  @override
  void visitExportDirective(analyzer_ast.ExportDirective node) {}

  @override
  void visitPartDirective(analyzer_ast.PartDirective node) {}

  @override
  void visitPartOfDirective(analyzer_ast.PartOfDirective node) {}

  @override
  void visitLibraryDirective(analyzer_ast.LibraryDirective node) {}

  /// Records a reference to the [element] named by the [token], if it's a top-level declaration.
  ///
  void _record(
    analyzer_element.Element? element,
    analyzer_token.Token token, {
    required bool isPrefixed,
    bool isSimpleInterpolation = false,
  }) {
    final topLevelElement = ProjectMerger._topLevelElement(element);
    if (topLevelElement == null || token.lexeme != topLevelElement.name) return;
    // References through third-party import prefixes are not ambiguous.
    if (isPrefixed && !merger._isMergedLibrary(topLevelElement.library)) return;
    references.add(
      _TopLevelReference(
        source: source,
        offset: token.offset,
        end: token.end,
        element: topLevelElement,
        isSimpleInterpolation: isSimpleInterpolation,
      ),
    );
  }

  /// Records a kept import prefix, which may be renamed to avoid clashes between the merged files.
  ///
  void _recordPrefixUsage(analyzer_token.Token token) => merger._prefixUsages.add((source: source, token: token));

  /// Removes the [prefix] of a reference to a merged library, e.g., `helpers.` in `helpers.value`.
  ///
  /// Returns whether the prefix was removed.
  ///
  bool _removePrefix(
    analyzer_token.Token prefix,
    analyzer_token.Token period,
    analyzer_element.Element? element,
    analyzer_ast.AstNode reference,
    String name,
  ) {
    final library = element?.library;
    if (!merger._isMergedLibrary(library)) return false;
    source.addEdit(prefix.offset, period.end, '');
    // Without the prefix, the name could be captured by a declaration in scope (e.g., a class member).
    final topLevelElement = ProjectMerger._topLevelElement(element);
    if (topLevelElement != null && _isShadowed(reference, name)) {
      merger._capturedTopLevelKeys.add(ProjectMerger._topLevelKey(topLevelElement));
    }
    return true;
  }

  /// Whether a declaration named [name] is in the lexical scope of the [reference], below the top level.
  ///
  static bool _isShadowed(analyzer_ast.AstNode reference, String name) {
    bool declares(Iterable<analyzer_token.Token?> tokens) => tokens.any((token) => token?.lexeme == name);
    Iterable<analyzer_token.Token?> parameterNames(analyzer_ast.FormalParameterList? list) => [
      for (final parameter in list?.parameters ?? const <analyzer_ast.FormalParameter>[]) parameter.name,
    ];
    Iterable<analyzer_token.Token?> typeParameterNames(analyzer_ast.TypeParameterList? list) => [
      for (final parameter in list?.typeParameters ?? const <analyzer_ast.TypeParameter>[]) parameter.name,
    ];
    Iterable<analyzer_token.Token> patternVariables(analyzer_ast.AstNode? node) {
      final collector = _PatternVariableCollector();
      node?.accept(collector);
      return collector.names;
    }

    Iterable<analyzer_token.Token> statementNames(List<analyzer_ast.Statement> statements) => [
      for (final statement in statements)
        ...switch (statement) {
          analyzer_ast.VariableDeclarationStatement(:final variables) => [
            for (final variable in variables.variables) variable.name,
          ],
          analyzer_ast.FunctionDeclarationStatement(:final functionDeclaration) => [functionDeclaration.name],
          analyzer_ast.PatternVariableDeclarationStatement() => patternVariables(statement),
          _ => const <analyzer_token.Token>[],
        },
    ];

    for (analyzer_ast.AstNode? node = reference.parent; node != null; node = node.parent) {
      final isShadowing = switch (node) {
        analyzer_ast.ClassDeclaration(:final typeParameters) ||
        analyzer_ast.MixinDeclaration(:final typeParameters) ||
        analyzer_ast.ExtensionDeclaration(:final typeParameters) => declares([
          ...typeParameterNames(typeParameters),
          ...ProjectMerger._memberNames(node as analyzer_ast.CompilationUnitMember),
        ]),
        analyzer_ast.EnumDeclaration(:final typeParameters, :final constants) => declares([
          ...typeParameterNames(typeParameters),
          ...ProjectMerger._memberNames(node),
          for (final constant in constants) constant.name,
        ]),
        analyzer_ast.ExtensionTypeDeclaration(:final typeParameters) => declares([
          ...typeParameterNames(typeParameters),
          ...ProjectMerger._memberNames(node),
        ]),
        analyzer_ast.MethodDeclaration(:final parameters, :final typeParameters) => declares([
          ...parameterNames(parameters),
          ...typeParameterNames(typeParameters),
        ]),
        analyzer_ast.FunctionExpression(:final parameters, :final typeParameters) => declares([
          ...parameterNames(parameters),
          ...typeParameterNames(typeParameters),
        ]),
        analyzer_ast.ConstructorDeclaration(:final parameters) => declares(parameterNames(parameters)),
        analyzer_ast.GenericTypeAlias(:final typeParameters) ||
        analyzer_ast.FunctionTypeAlias(:final typeParameters) ||
        analyzer_ast.ClassTypeAlias(:final typeParameters) ||
        analyzer_ast.GenericFunctionType(:final typeParameters) => declares(typeParameterNames(typeParameters)),
        analyzer_ast.Block(:final statements) => declares(statementNames(statements)),
        // The statements of a switch case are a scope of their own, along with the pattern variables of the case.
        analyzer_ast.SwitchMember(:final statements) => declares([
          ...statementNames(statements),
          if (node is analyzer_ast.SwitchPatternCase) ...patternVariables(node.guardedPattern),
        ]),
        analyzer_ast.ForStatement(:final forLoopParts) || analyzer_ast.ForElement(:final forLoopParts) => declares([
          ...switch (forLoopParts) {
            analyzer_ast.ForPartsWithDeclarations(:final variables) => [
              for (final variable in variables.variables) variable.name,
            ],
            analyzer_ast.ForEachPartsWithDeclaration(:final loopVariable) => [loopVariable.name],
            _ => patternVariables(forLoopParts),
          },
        ]),
        analyzer_ast.CatchClause(:final exceptionParameter, :final stackTraceParameter) => declares([
          exceptionParameter?.name,
          stackTraceParameter?.name,
        ]),
        analyzer_ast.SwitchExpressionCase() || analyzer_ast.IfStatement() || analyzer_ast.IfElement() => declares(patternVariables(node)),
        _ => false,
      };
      if (isShadowing) return true;
    }
    return false;
  }

  @override
  void visitSimpleIdentifier(analyzer_ast.SimpleIdentifier node) {
    final element = node.element;
    final forEachParts = node.parent;
    if (forEachParts is analyzer_ast.ForEachPartsWithIdentifier &&
        forEachParts.identifier == node &&
        element is! analyzer_element.LocalVariableElement &&
        element is! analyzer_element.FormalParameterElement) {
      final topLevelElement = ProjectMerger._topLevelElement(element);
      merger._forInNames.putIfAbsent(node.name, () => {}).addAll([
        if (topLevelElement != null) ProjectMerger._topLevelKey(topLevelElement),
      ]);
    }
    if (element is analyzer_element.PrefixElement) {
      final parent = node.parent;
      final isMergedDeferred = element.imports.every((import) => merger._isMergedLibrary(import.importedLibrary));
      if (parent is analyzer_ast.PrefixedIdentifier &&
          parent.prefix == node &&
          parent.identifier.name == 'loadLibrary' &&
          isMergedDeferred) {
        // Tear-off of the deferred loading of a merged library, which is always loaded.
        source.addEdit(parent.offset, parent.end, '(() => Future<void>.value())');
      } else if (parent is analyzer_ast.PrefixedIdentifier && parent.prefix == node) {
        if (!_removePrefix(
          node.token,
          parent.period,
          parent.identifier.element ?? ObjectCollector.assignedElement(parent.identifier),
          parent,
          parent.identifier.name,
        )) {
          _recordPrefixUsage(node.token);
        }
      } else if (parent is analyzer_ast.MethodInvocation && parent.target == node) {
        if (parent.methodName.name == 'loadLibrary' && element.imports.every((import) => merger._isMergedLibrary(import.importedLibrary))) {
          // Deferred loading of a merged library, which is always loaded.
          source.addEdit(parent.offset, parent.end, 'Future<void>.value()');
        } else if (!_removePrefix(node.token, parent.operator!, parent.methodName.element, parent, parent.methodName.name)) {
          _recordPrefixUsage(node.token);
        }
      } else {
        _recordPrefixUsage(node.token);
      }
      return;
    }
    var resolved = element ?? ObjectCollector.assignedElement(node);
    if (resolved is analyzer_element.ConstructorElement) {
      resolved = node.name == resolved.enclosingElement.name ? resolved.enclosingElement : null;
    }
    final parent = node.parent;
    final isPrefixed = switch (parent) {
      analyzer_ast.PrefixedIdentifier(:final identifier, :final prefix) =>
        identifier == node && prefix.element is analyzer_element.PrefixElement,
      analyzer_ast.MethodInvocation(:final methodName, :final target) =>
        methodName == node && target is analyzer_ast.SimpleIdentifier && target.element is analyzer_element.PrefixElement,
      _ => false,
    };
    // Members accessed through a target (e.g., `object.member`) can't be top-level declarations.
    if (parent is analyzer_ast.PrefixedIdentifier && parent.identifier == node && !isPrefixed) return;
    if (parent is analyzer_ast.PropertyAccess && parent.propertyName == node) return;
    if (parent is analyzer_ast.MethodInvocation && parent.methodName == node && parent.target != null && !isPrefixed) return;
    _record(
      resolved,
      node.token,
      isPrefixed: isPrefixed,
      isSimpleInterpolation: parent is analyzer_ast.InterpolationExpression && parent.rightBracket == null,
    );
  }

  @override
  void visitExtensionOverride(analyzer_ast.ExtensionOverride node) {
    final importPrefix = node.importPrefix;
    var isPrefixed = importPrefix != null;
    if (importPrefix != null) {
      if (_removePrefix(importPrefix.name, importPrefix.period, node.element, node, node.name.lexeme)) {
        isPrefixed = false;
      } else {
        _recordPrefixUsage(importPrefix.name);
      }
    }
    _record(node.element, node.name, isPrefixed: isPrefixed);
    super.visitExtensionOverride(node);
  }

  @override
  void visitNamedType(analyzer_ast.NamedType node) {
    final importPrefix = node.importPrefix;
    var isPrefixed = importPrefix != null;
    if (importPrefix != null) {
      if (_removePrefix(importPrefix.name, importPrefix.period, node.element, node, node.name.lexeme)) {
        isPrefixed = false;
      } else {
        _recordPrefixUsage(importPrefix.name);
      }
    }
    _record(node.element, node.name, isPrefixed: isPrefixed);
    super.visitNamedType(node);
  }
}

/// Renames the private class and extension members of the merged libraries, according to the [renames].
///
class _PrivateMemberVisitor extends analyzer_visitor.RecursiveAstVisitor<void> {
  _PrivateMemberVisitor({
    required this.source,
    required this.renames,
  });

  final _MergedSource source;

  /// New names, mapped by the private member keys.
  ///
  final Map<String, String> renames;

  void _rename(analyzer_element.Element? element, analyzer_token.Token token) {
    final newName = renames[ProjectMerger._privateMemberKey(element)];
    if (newName != null && token.lexeme.startsWith('_')) source.addEdit(token.offset, token.end, newName);
  }

  @override
  void visitImportDirective(analyzer_ast.ImportDirective node) {}

  @override
  void visitExportDirective(analyzer_ast.ExportDirective node) {}

  @override
  void visitLibraryDirective(analyzer_ast.LibraryDirective node) {}

  @override
  void visitPartDirective(analyzer_ast.PartDirective node) {}

  @override
  void visitPartOfDirective(analyzer_ast.PartOfDirective node) {}

  @override
  void visitMethodDeclaration(analyzer_ast.MethodDeclaration node) {
    _rename(node.declaredFragment?.element, node.name);
    super.visitMethodDeclaration(node);
  }

  @override
  void visitVariableDeclaration(analyzer_ast.VariableDeclaration node) {
    _rename(node.declaredFragment?.element, node.name);
    super.visitVariableDeclaration(node);
  }

  @override
  void visitRepresentationDeclaration(analyzer_ast.RepresentationDeclaration node) {
    _rename(node.fieldFragment?.element, node.fieldName);
    super.visitRepresentationDeclaration(node);
  }

  @override
  void visitFieldFormalParameter(analyzer_ast.FieldFormalParameter node) {
    _rename(node.declaredFragment?.element, node.name);
    super.visitFieldFormalParameter(node);
  }

  @override
  void visitSimpleIdentifier(analyzer_ast.SimpleIdentifier node) {
    final element = node.element ?? ObjectCollector.assignedElement(node);
    if (element != null) {
      _rename(element, node.token);
      return;
    }
    // A dynamic access to a private member (e.g., `(value as dynamic)._name`) refers to the members of this library.
    final parent = node.parent;
    final isMemberAccess =
        parent is analyzer_ast.PropertyAccess && parent.propertyName == node ||
        parent is analyzer_ast.PrefixedIdentifier &&
            parent.identifier == node &&
            parent.prefix.element is! analyzer_element.PrefixElement ||
        parent is analyzer_ast.MethodInvocation && parent.methodName == node && (parent.target != null || parent.isCascaded);
    final newName = renames['${source.result.libraryElement.uri}#${node.name}'];
    if (isMemberAccess && newName != null) source.addEdit(node.offset, node.end, newName);
  }

  @override
  void visitPatternField(analyzer_ast.PatternField node) {
    final name = node.name;
    final newName = renames[ProjectMerger._privateMemberKey(node.element)];
    if (name != null && newName != null) {
      final nameToken = name.name;
      if (nameToken != null) {
        _rename(node.element, nameToken);
      } else {
        // Shorthand field (e.g., `Point(:var _x)`), the new name is inserted before the colon.
        source.addEdit(name.colon.offset, name.colon.offset, newName);
      }
    }
    super.visitPatternField(node);
  }
}

/// Rewrites the implicit extension member invocations to explicit extension overrides,
/// for the member names which become ambiguous once the libraries are merged.
///
class _ExtensionOverrideVisitor extends analyzer_visitor.RecursiveAstVisitor<void> {
  _ExtensionOverrideVisitor({
    required this.newValueName,
    required this.source,
    required this.memberNames,
    required this.overrideName,
    required this.explicitOffsets,
  });

  /// Positions of the invocations on the implicit `this` made explicit, which don't need other qualification.
  ///
  final Set<(_MergedSource, int)> explicitOffsets;

  /// Returns a unique name for the closure parameters of the null-shorting rewrites.
  ///
  final String Function() newValueName;

  /// Rewrites of the null-aware operators of null-shorting chains, with the extensions applied after them
  /// (outermost first) and the end of the outermost invocation.
  ///
  final nullAwareRewrites = <analyzer_token.Token, ({List<String> names, int end, String value})>{};

  /// Returns the null-aware operator short-circuiting the [target] of an invocation, if any.
  ///
  static analyzer_token.Token? _nullShortingOperator(analyzer_ast.Expression target) {
    analyzer_ast.Expression? current = target;
    while (current != null) {
      switch (current) {
        case analyzer_ast.PropertyAccess(:final operator, :final target):
          if (operator.type == analyzer_token.TokenType.QUESTION_PERIOD) return operator;
          current = target;
        case analyzer_ast.MethodInvocation(:final operator, :final target):
          if (operator?.type == analyzer_token.TokenType.QUESTION_PERIOD) return operator;
          current = target;
        case analyzer_ast.IndexExpression(:final question, :final target):
          if (question != null) return question;
          current = target;
        case analyzer_ast.PostfixExpression(:final operand, :final operator) when operator.type == analyzer_token.TokenType.BANG:
          current = operand;
        default:
          return null;
      }
    }
    return null;
  }

  /// The null-shorting chain continuing after the [node] (e.g., with `.length` in `a?.b.ext().length`).
  ///
  static analyzer_ast.AstNode _nullShortingChain(analyzer_ast.AstNode node) {
    var current = node;
    while (true) {
      final parent = current.parent;
      final continuesChain = switch (parent) {
        analyzer_ast.PropertyAccess(:final target) ||
        analyzer_ast.MethodInvocation(:final target) ||
        analyzer_ast.IndexExpression(:final target) => target == current,
        analyzer_ast.PostfixExpression(:final operand, :final operator) =>
          operand == current && operator.type == analyzer_token.TokenType.BANG,
        analyzer_ast.AssignmentExpression(:final leftHandSide) => leftHandSide == current,
        _ => false,
      };
      if (!continuesChain) return current;
      current = parent!;
    }
  }

  /// Whether the [node] contains an `await` expression, which can't be moved into a closure.
  ///
  static bool _containsAwait(analyzer_ast.AstNode node) {
    final collector = _AwaitCollector();
    node.accept(collector);
    return collector.found;
  }

  /// Applies the recorded rewrites of null-aware operators, using the [let] extension method.
  ///
  void applyNullAwareRewrites(String let) {
    for (final entry in nullAwareRewrites.entries) {
      final operator = entry.key;
      final rewrite = entry.value;
      final isIndex = operator.type == analyzer_token.TokenType.QUESTION;
      final access = isIndex ? '${rewrite.value}[' : '${rewrite.value}.';
      final end = isIndex ? operator.next!.end : operator.end;
      source.addEdit(operator.offset, end, '?.$let((${rewrite.value}) => ${rewrite.names.map((name) => '$name(').join()}$access');
      source.addEdit(rewrite.end, rewrite.end, ')');
    }
  }

  final _MergedSource source;

  /// Names of the members of the extensions which become visible once merged.
  ///
  final Set<String> memberNames;

  /// Returns the name used to explicitly apply an extension, or `null` if it can't be referenced.
  ///
  final String? Function(analyzer_element.ExtensionElement extension) overrideName;

  /// Returns the extension declaring the instance member an [element] reference resolves to.
  ///
  static analyzer_element.ExtensionElement? _extensionOf(analyzer_element.Element? element) {
    final base = element?.baseElement;
    final enclosingElement = base?.enclosingElement;
    if (base is! analyzer_element.ExecutableElement || base.isStatic) return null;
    return enclosingElement is analyzer_element.ExtensionElement ? enclosingElement : null;
  }

  void _warn(analyzer_ast.AstNode node, String name) {
    final location = source.result.lineInfo.getLocation(node.offset);
    print(
      'Warning: ${source.filePath}:${location.lineNumber}: the "$name" extension member may resolve '
      'to a different extension in the merged file, and could not be made explicit.',
    );
  }

  /// Applies the extension declaring the [element] explicitly to the [target] of an invocation.
  ///
  void _override({
    required analyzer_ast.AstNode node,
    required analyzer_element.Element? element,
    required String name,
    required analyzer_ast.Expression? target,
    required bool isCascaded,
    required analyzer_token.Token nameToken,
  }) {
    final extension = _extensionOf(element);
    if (extension == null || !memberNames.contains(name) || target is analyzer_ast.ExtensionOverride) return;
    final isImplicitThis = target == null && !isCascaded;
    if (isImplicitThis) {
      // Members of the enclosing extension itself are resolved lexically.
      final enclosing = node.thisOrAncestorOfType<analyzer_ast.CompilationUnitMember>()?.declaredFragment?.element;
      if (enclosing is analyzer_element.ExtensionElement &&
          ProjectMerger._extensionKey(enclosing) == ProjectMerger._extensionKey(extension)) {
        return;
      }
    }
    final extensionName = overrideName(extension);
    if (isCascaded || target is analyzer_ast.SuperExpression || extensionName == null) {
      _warn(node, name);
      return;
    }
    if (isImplicitThis) {
      // An invocation on the implicit `this` (e.g., `describe()` in a class) is applied explicitly to `this`.
      explicitOffsets.add((source, nameToken.offset));
      final parent = node.parent;
      if (parent is analyzer_ast.InterpolationExpression && parent.rightBracket == null) {
        source.addEdit(nameToken.offset, nameToken.offset, '{$extensionName(this).', priority: 0);
        source.addEdit(nameToken.end, nameToken.end, '}');
      } else {
        source.addEdit(nameToken.offset, nameToken.offset, '$extensionName(this).', priority: 0);
      }
      return;
    }
    // Within a null-shorting chain (e.g., `user?.name.initials`), the override is applied to the value after the
    // null-aware operator, in a closure invoked with the same operator: `user?.let((v) => StringX(v.name).initials)`.
    final nullAwareOperator = _nullShortingOperator(target!);
    if (nullAwareOperator != null) {
      final chain = _nullShortingChain(node);
      if (element is analyzer_element.SetterElement || _containsAwait(chain)) {
        _warn(node, name);
        return;
      }
      final rewrite = nullAwareRewrites.putIfAbsent(
        nullAwareOperator,
        () => (names: <String>[], end: chain.end, value: newValueName()),
      );
      rewrite.names.add(extensionName);
      source.addEdit(target.end, target.end, ')');
      return;
    }
    source.addEdit(target.offset, target.offset, '$extensionName(', priority: 0);
    source.addEdit(target.end, target.end, ')');
  }

  @override
  void visitComment(analyzer_ast.Comment node) {}

  @override
  void visitSimpleIdentifier(analyzer_ast.SimpleIdentifier node) {
    final parent = node.parent;
    // Getters and setters invoked on the implicit `this`, the other forms are handled by their parents.
    if (parent is analyzer_ast.PrefixedIdentifier && parent.identifier == node ||
        parent is analyzer_ast.PropertyAccess && parent.propertyName == node ||
        parent is analyzer_ast.MethodInvocation && parent.methodName == node ||
        parent is analyzer_ast.Label) {
      return;
    }
    if (parent is analyzer_ast.ForEachPartsWithIdentifier) {
      // For-in loop identifiers can't be applied explicitly.
      final element = node.element ?? ObjectCollector.assignedElement(node);
      if (_extensionOf(element) != null && memberNames.contains(node.name)) _warn(node, node.name);
      return;
    }
    _override(
      node: node,
      element: node.element ?? ObjectCollector.assignedElement(node),
      name: node.name,
      target: null,
      isCascaded: false,
      nameToken: node.token,
    );
  }

  @override
  void visitPatternField(analyzer_ast.PatternField node) {
    // Extension getters can't be applied explicitly in object patterns.
    final extension = _extensionOf(node.element);
    final name = node.element?.name;
    if (extension != null && name != null && memberNames.contains(name)) _warn(node, name);
    super.visitPatternField(node);
  }

  @override
  void visitImportDirective(analyzer_ast.ImportDirective node) {}

  @override
  void visitExportDirective(analyzer_ast.ExportDirective node) {}

  @override
  void visitLibraryDirective(analyzer_ast.LibraryDirective node) {}

  @override
  void visitPartDirective(analyzer_ast.PartDirective node) {}

  @override
  void visitPartOfDirective(analyzer_ast.PartOfDirective node) {}

  @override
  void visitMethodInvocation(analyzer_ast.MethodInvocation node) {
    _override(
      node: node,
      element: node.methodName.element,
      name: node.methodName.name,
      target: node.target,
      isCascaded: node.isCascaded,
      nameToken: node.methodName.token,
    );
    super.visitMethodInvocation(node);
  }

  @override
  void visitPropertyAccess(analyzer_ast.PropertyAccess node) {
    _override(
      node: node,
      element: node.propertyName.element ?? ObjectCollector.assignedElement(node.propertyName),
      name: node.propertyName.name,
      target: node.target,
      isCascaded: node.isCascaded,
      nameToken: node.propertyName.token,
    );
    super.visitPropertyAccess(node);
  }

  @override
  void visitPrefixedIdentifier(analyzer_ast.PrefixedIdentifier node) {
    _override(
      node: node,
      element: node.identifier.element ?? ObjectCollector.assignedElement(node.identifier),
      name: node.identifier.name,
      target: node.prefix,
      isCascaded: false,
      nameToken: node.identifier.token,
    );
    super.visitPrefixedIdentifier(node);
  }

  void _checkOperator(analyzer_ast.AstNode node, analyzer_element.Element? element) {
    final extension = _extensionOf(element);
    final name = element?.name;
    if (extension != null && name != null && memberNames.contains(name)) _warn(node, name);
  }

  @override
  void visitBinaryExpression(analyzer_ast.BinaryExpression node) {
    _checkOperator(node, node.element);
    super.visitBinaryExpression(node);
  }

  @override
  void visitIndexExpression(analyzer_ast.IndexExpression node) {
    _checkOperator(node, node.element);
    super.visitIndexExpression(node);
  }

  @override
  void visitPrefixExpression(analyzer_ast.PrefixExpression node) {
    _checkOperator(node, node.element);
    super.visitPrefixExpression(node);
  }

  @override
  void visitFunctionExpressionInvocation(analyzer_ast.FunctionExpressionInvocation node) {
    _checkOperator(node, node.element);
    super.visitFunctionExpressionInvocation(node);
  }
}

/// Qualifies the unqualified references to inherited instance members with `this`,
/// for the member names which are visible at the top level of the merged file.
///
class _ImplicitThisVisitor extends analyzer_visitor.RecursiveAstVisitor<void> {
  _ImplicitThisVisitor({
    required this.merger,
    required this.source,
    required this.scopeNames,
  });

  final ProjectMerger merger;

  final _MergedSource source;

  /// Names visible at the top level of the merged file.
  ///
  final Set<String> scopeNames;

  @override
  void visitImportDirective(analyzer_ast.ImportDirective node) {}

  @override
  void visitExportDirective(analyzer_ast.ExportDirective node) {}

  @override
  void visitLibraryDirective(analyzer_ast.LibraryDirective node) {}

  @override
  void visitPartDirective(analyzer_ast.PartDirective node) {}

  @override
  void visitPartOfDirective(analyzer_ast.PartOfDirective node) {}

  @override
  void visitComment(analyzer_ast.Comment node) {}

  @override
  void visitConstructorFieldInitializer(analyzer_ast.ConstructorFieldInitializer node) {
    // The field name of an initializer is not an expression, only its value is visited.
    node.expression.accept(this);
  }

  @override
  void visitSimpleIdentifier(analyzer_ast.SimpleIdentifier node) {
    final parent = node.parent;
    // Only unqualified references can resolve through the implicit `this`.
    if (parent is analyzer_ast.PrefixedIdentifier && parent.identifier == node ||
        parent is analyzer_ast.PropertyAccess && parent.propertyName == node ||
        parent is analyzer_ast.MethodInvocation && parent.methodName == node && (parent.target != null || parent.isCascaded) ||
        parent is analyzer_ast.Label ||
        parent is analyzer_ast.ConstructorName ||
        parent is analyzer_ast.Combinator) {
      return;
    }
    final element = (node.element ?? ObjectCollector.assignedElement(node))?.baseElement;
    if (element is! analyzer_element.ExecutableElement && element is! analyzer_element.FieldElement) return;
    if (element is analyzer_element.ExecutableElement && element.isStatic) return;
    if (element is analyzer_element.FieldElement && element.isStatic) return;
    final declarer = element!.enclosingElement;
    if (declarer is! analyzer_element.InstanceElement || element is analyzer_element.ConstructorElement) return;
    // Members declared by the enclosing declaration are found in its scope, before the top-level ones.
    final enclosingDeclaration = node.thisOrAncestorOfType<analyzer_ast.CompilationUnitMember>();
    final enclosingElement = enclosingDeclaration?.declaredFragment?.element;
    if (enclosingElement == null || enclosingElement == declarer.baseElement) return;
    final name = merger._mergedMemberName(declarer, node.name);
    if (!scopeNames.contains(name) || merger._explicitExtensionOffsets.contains((source, node.offset))) return;
    if (parent is analyzer_ast.ForEachPartsWithIdentifier) {
      // For-in loop identifiers can't be qualified, first-party top-level declarations are renamed instead.
      final location = source.result.lineInfo.getLocation(node.offset);
      print(
        'Warning: ${source.filePath}:${location.lineNumber}: the "${node.name}" loop variable may refer to an imported '
        'declaration in the merged file.',
      );
      return;
    }
    if (parent is analyzer_ast.InterpolationExpression && parent.rightBracket == null) {
      // Simple interpolation (e.g., `$position`) is converted to `${this.position}`.
      source.addEdit(node.offset, node.offset, '{this.', priority: 0);
      source.addEdit(node.end, node.end, '}');
    } else {
      source.addEdit(node.offset, node.offset, 'this.', priority: 0);
    }
  }
}

/// Collects the names of the variables declared by patterns.
